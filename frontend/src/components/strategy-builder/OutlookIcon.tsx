/** Bear icon is 75% larger than the requested size token. */
function bearishSizeClass(className: string): string {
  return className
    .replace(/\bsize-5\b/, "size-[2.1875rem]")
    .replace(/\bsize-6\b/, "size-[2.625rem]");
}

